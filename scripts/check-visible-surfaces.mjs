// Regression: shared visible surfaces stay correct without entering Mesh mode.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {createRequire} from 'node:module';
import {pathToFileURL} from 'node:url';
import ts from 'typescript';
import {NullEngine} from '@babylonjs/core/Engines/nullEngine.js';
import {Scene} from '@babylonjs/core/scene.js';
import {ArcRotateCamera} from '@babylonjs/core/Cameras/arcRotateCamera.js';
import {Vector3,Matrix} from '@babylonjs/core/Maths/math.vector.js';
import {CreateSphere} from '@babylonjs/core/Meshes/Builders/sphereBuilder.js';
import {CreateGround} from '@babylonjs/core/Meshes/Builders/groundBuilder.js';
import {Skeleton} from '@babylonjs/core/Bones/skeleton.js';
import {Bone} from '@babylonjs/core/Bones/bone.js';
import {MorphTarget} from '@babylonjs/core/Morph/morphTarget.js';
import {MorphTargetManager} from '@babylonjs/core/Morph/morphTargetManager.js';
import '@babylonjs/core/Culling/ray.js';
const require=createRequire(import.meta.url),urls=new Map();
function moduleURL(filename){
 filename=path.resolve(filename);if(urls.has(filename))return urls.get(filename);
 let code=ts.transpileModule(fs.readFileSync(filename,'utf8'),{compilerOptions:{target:ts.ScriptTarget.ES2023,module:ts.ModuleKind.ESNext}}).outputText;
 code=code.replace(/from ['"]([^'"]+)['"]/g,(_,id)=>`from '${id.startsWith('.')?moduleURL(path.resolve(path.dirname(filename),id+'.ts')):pathToFileURL(require.resolve(id)).href}'`);
 const url='data:text/javascript;base64,'+Buffer.from(code).toString('base64');urls.set(filename,url);return url;
}
const {prepareSurface,invalidateSurfaces,surfacePositions,surfaceNormal}=await import(moduleURL('src/core/surface.ts'));
const {smartSelect}=await import(moduleURL('src/edit/smartSelect.ts'));
const {FaceSelection}=await import(moduleURL('src/edit/selection.ts'));
const engine=new NullEngine({renderWidth:512,renderHeight:512}),scene=new Scene(engine);
engine.getCaps().maxVertexUniformVectors=1024;
const camera=new ArcRotateCamera('camera',Math.PI/2,Math.PI/2,8,new Vector3(3,0,0),scene);scene.activeCamera=camera;
const mesh=CreateSphere('posed',{diameter:1,segments:12},scene),skeleton=new Skeleton('rig','rig',scene),bone=new Bone('root',skeleton,null,Matrix.Identity());
mesh.skeleton=skeleton;const count=mesh.getTotalVertices(),weights=new Float32Array(count*4);for(let i=0;i<count;i++)weights[i*4]=1;
mesh.setVerticesData('matricesIndices',new Float32Array(count*4));mesh.setVerticesData('matricesWeights',weights);
bone.updateMatrix(Matrix.Translation(3,0,0),false,true);skeleton.prepare(true);scene.render();
assert.equal(scene.pick(256,256,m=>m===mesh)?.hit,false);
let refreshes=0;const refresh=mesh.refreshBoundingInfo.bind(mesh);mesh.refreshBoundingInfo=(...args)=>{refreshes++;return refresh(...args)};
prepareSurface(mesh);assert.equal(scene.pick(256,256,m=>m===mesh)?.hit,true);prepareSurface(mesh);assert.equal(refreshes,1,'Repeated picks in one frame reuse preparation');
scene.render();prepareSurface(mesh);assert.equal(refreshes,1,'Camera-only frames must not reskin unchanged vertices');
const getPositionData=mesh.getPositionData;mesh.getPositionData=()=>{throw Error('Normal must not reskin the mesh')};
assert.ok(surfaceNormal(mesh,0));mesh.getPositionData=getPositionData;
bone.updateMatrix(Matrix.Translation(5,0,0),false,true);invalidateSurfaces();prepareSurface(mesh);assert.equal(refreshes,2);assert.ok(mesh.getBoundingInfo().boundingBox.minimum.x>4);
const morph=CreateSphere('morph',{diameter:1,segments:12},scene),manager=new MorphTargetManager(scene),target=MorphTarget.FromMesh(morph,'shift',1);const positions=Float32Array.from(morph.getVerticesData('position'));for(let i=0;i<positions.length;i+=3)positions[i]+=3;target.setPositions(positions);manager.addTarget(target);morph.morphTargetManager=manager;
invalidateSurfaces();prepareSurface(morph);assert.equal(scene.pick(256,256,m=>m===morph)?.hit,true,'Morph-only model picking follows its visible geometry');
assert.ok(morph.getBoundingInfo().boundingBox.minimum.x>2);
const editor={scene,overlays:new Set(),notify(){},invalidate(){}};
const selection=new FaceSelection(editor,{meshes:[morph]});
smartSelect(selection,morph,0,.3,true);const first=selection.count;assert.ok(first>0);
selection.clear();target.influence=0;invalidateSurfaces();prepareSurface(morph);smartSelect(selection,morph,0,.3,true);assert.equal(selection.count,first,'Translation-only shape keys preserve smart selection');
assert.ok(surfacePositions(morph)[0]<1,'Updated influence is read immediately');
const ground=CreateGround('fold',{width:2,height:2,subdivisions:1},scene),foldManager=new MorphTargetManager(scene),fold=MorphTarget.FromMesh(ground,'fold',0);
const folded=Float32Array.from(ground.getVerticesData('position'));folded[1]=5;fold.setPositions(folded);foldManager.addTarget(fold);ground.morphTargetManager=foldManager;
const foldedSelection=new FaceSelection(editor,{meshes:[ground]});
smartSelect(foldedSelection,ground,0,0,true);assert.equal(foldedSelection.count,2,'A flat quad selects both faces');
foldedSelection.clear();fold.influence=1;invalidateSurfaces();smartSelect(foldedSelection,ground,0,0,true);assert.equal(foldedSelection.count,1,'A changed crease must not reuse flat face normals');foldedSelection.dispose();
selection.dispose();scene.dispose();engine.dispose();console.log('Native picking, posed and morph bounds, preparation reuse/invalidation and smart selection pass.');
